#!/usr/bin/env python3
"""Generate tiny inline painted previews; needs Pillow with WebP support.

This only resizes/encodes existing artwork. Full-resolution sources and world
coordinates remain unchanged. Run before prepare_web.py when source art changes.
"""
import base64
import io
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
KEYS = ['town', 'forest', 'heyang', 'temple', 'interiors', 'outskirts',
        'riverwoods', 'hilltrail', 'forestcave', 'people']
encoded = {}
for key in KEYS:
    source = Image.open(ROOT / 'assets' / ('world-' + key + '.png'))
    width, height = source.size
    source.thumbnail((384, 384) if key == 'people' else (256, 256), Image.Resampling.LANCZOS)
    stream = io.BytesIO()
    source.save(stream, format='WEBP', quality=65 if key == 'people' else 55, method=6)
    encoded[key] = [width, height, base64.b64encode(stream.getvalue()).decode('ascii')]

program = '''/* Tiny authored scenery and people, bundled so slow networks never show an empty world.
 * Generated by prepare_previews.py; full-resolution assets replace these after loading.
 * SVG wrappers retain original intrinsic dimensions, preserving atlas crop coordinates.
 */
(function(){
'use strict';
const data=DATA,images=new Map(),listeners=new Set();
function request(key){
 if(!data[key])return null;
 if(images.has(key))return images.get(key);
 const [width,height,pixels]=data[key],img=new Image();
 images.set(key,img);
 img.decoding='async';
 img.onload=()=>{for(const listener of listeners){try{listener(key,img);}catch{}}};
 img.src='data:image/svg+xml;charset=utf-8,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="'+width+'" height="'+height+'" viewBox="0 0 '+width+' '+height+'"><image width="'+width+'" height="'+height+'" preserveAspectRatio="none" href="data:image/webp;base64,'+pixels+'"/></svg>');
 return img;
}
window.JianghuPreviews={
 getImage(key){const img=request(key);return img&&img.complete&&img.naturalWidth>0?img:null;},
 subscribe(listener){listeners.add(listener);return()=>listeners.delete(listener);}
};
// The initial scene and NPCs begin decoding alongside the rest of the program.
request('town');request('people');
})();
'''.replace('DATA', json.dumps(encoded, separators=(',', ':')))
(ROOT / 'scene-previews.js').write_text(program)
print('Generated scene-previews.js: %d bytes' % len(program.encode()))
